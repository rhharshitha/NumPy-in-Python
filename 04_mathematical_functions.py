import numpy as np

arr = np.array([10, 20, 30, 40, 50])

print("Sum:", np.sum(arr))
print("Mean:", np.mean(arr))
print("Maximum:", np.max(arr))
print("Minimum:", np.min(arr))
print("Standard Deviation:", np.std(arr))

# Expected Output:
# Sum: 150
# Mean: 30.0
# Maximum: 50
# Minimum: 10
# Standard Deviation: 14.142135623730951
